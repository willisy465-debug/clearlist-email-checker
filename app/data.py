def in_domain_set(domain: str, pool: frozenset[str]) -> bool:
    domain = domain.lower().rstrip(".")
    if domain in pool:
        return True
    labels = domain.split(".")
    for index in range(1, len(labels) - 1):
        if ".".join(labels[index:]) in pool:
            return True
    return False


def is_bot_or_gibberish_local(local: str) -> tuple[bool, str]:
    """Detect bot-generated, poisoned, or high-entropy gibberish local parts."""
    base = local.split("+", 1)[0].lower()
    clean = re.sub(r"[._-]", "", base)
    if not clean:
        return False, ""

    # 1. Pure numeric or mostly numeric local part (e.g. 8493029483@domain.com)
    digits = sum(1 for c in clean if c.isdigit())
    if len(clean) >= 7 and digits == len(clean):
        return True, "Mailbox name is a numeric string typical of automated bot signups."
    if len(clean) >= 10 and digits / len(clean) >= 0.70:
        return True, "Mailbox name is heavily numeric, which is a strong bot/poisoned signup signal."

    # 2. Keyboard walk patterns
    for walk in _KEYBOARD_WALKS:
        if walk in clean:
            return True, f"Mailbox name contains keyboard-walk pattern '{walk}'."

    # 3. Hex / UUID-like machine token (e.g. a8f9c20d4e1b7a93@...)
    if len(clean) >= 14 and re.fullmatch(r"[0-9a-f]+", clean) and digits >= 4:
        return True, "Mailbox name looks like a machine-generated hexadecimal hash or spam-trap seed."

    # 4. Consonant cluster / vowel starvation in long strings (e.g. xkjqwzptlmn@...)
    letters = [c for c in clean if c.isalpha()]
    if len(letters) >= 9:
        vowels = sum(1 for c in letters if c in "aeiouy")
        if vowels == 0 or (len(letters) >= 11 and vowels / len(letters) < 0.13):
            return True, "Mailbox name has unnatural character entropy (vowel starvation) typical of list-poisoning bots."

    # 5. High Shannon entropy on long random strings
    if len(clean) >= 16:
        freq: dict[str, int] = {}
        for ch in clean:
            freq[ch] = freq.get(ch, 0) + 1
        entropy = -sum((count / len(clean)) * math.log2(count / len(clean)) for count in freq.values())
        if entropy >= 3.85 and digits >= 3:
            return True, "Mailbox name has high randomness/entropy typical of seeded spam traps or bot traffic."

    return False, ""


def local_kinds(local: str) -> list[str]:
    base = local.split("+", 1)[0]
    key = re.sub(r"[._-]", "", base).lower()
    if not key:
        return []
    kinds: list[str] = []
    if key in TRAP or any(key.startswith(prefix) for prefix in ("spamtrap", "honeypot", "blackhole", "abuse", "postmaster", "mailerdaemon")):
        kinds.append("trap")
    if key in LITIGATOR_LOCAL or any(
        token in base.lower() for token in ("tcpa", "gdpr", "litigat", "classaction", "subpoena", "dmca")
    ):
        kinds.append("litigator")
    if key in COMPLAINER_LOCAL:
        kinds.append("complainer")
    if key in ROLE and "trap" not in kinds and "litigator" not in kinds:
        kinds.append("role")
    if key in TEST:
        kinds.append("test")
    is_bot, _ = is_bot_or_gibberish_local(local)
    if is_bot and "test" not in kinds:
        kinds.append("bot")
    return kinds


def damerau(left: str, right: str) -> int:
    if abs(len(left) - len(right)) > 1:
        return 2
    rows = len(left) + 1
    cols = len(right) + 1
    grid = [[0] * cols for _ in range(rows)]
    for i in range(rows):
        grid[i][0] = i
    for j in range(cols):
        grid[0][j] = j
    for i in range(1, rows):
        for j in range(1, cols):
            cost = 0 if left[i - 1] == right[j - 1] else 1
            grid[i][j] = min(
                grid[i - 1][j] + 1,
                grid[i][j - 1] + 1,
                grid[i - 1][j - 1] + cost,
            )
            if (
                i > 1
                and j > 1
                and left[i - 1] == right[j - 2]
                and left[i - 2] == right[j - 1]
            ):
                grid[i][j] = min(grid[i][j], grid[i - 2][j - 2] + 1)
    return grid[-1][-1]


def suggest_typo(domain: str, domain_exists: bool) -> str | None:
    """Suggest a popular domain for an obvious typo."""

    domain = domain.lower().rstrip(".")
    mapped = TYPOS.get(domain)
    if mapped and mapped != domain:
        return mapped
    if domain_exists or len(domain) < 10:
        return None
    for candidate in POPULAR:
        if abs(len(candidate) - len(domain)) > 1:
            continue
        if damerau(domain, candidate) == 1:
            return candidate
    return None
